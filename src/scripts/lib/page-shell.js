// The one page shell (head, header, footer, consent banner) for every GENERATED page: the blog
// (scripts/build-blog.js) and /legal (scripts/build-legal.js). It mirrors privacy.html / 404.html
// with root-absolute URLs (the pages are served without an extension and the blog lives one
// directory down, so relative URLs would break). A nav or footer change has to be made here AND in
// index.html, privacy.html and 404.html - see CLAUDE.md.

const { SITE } = require('./pages');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// The site writes a dash as " - " (no em or en dashes). Where a line wraps at the space before it,
// the next line starts with "- " and reads like a list bullet, so in visible text the space before
// the dash is a no-break space. Meta tags and JSON-LD keep the plain text. The no-break space is
// spelled out rather than typed, because a literal one is invisible and editors normalise it away.
const NBSP = String.fromCharCode(0xa0);
const glueDash = (s) => s.replace(/ - /g, `${NBSP}- `);

